    private val glyphs: Map<Char, BooleanArray> = raw.mapValues { (c, rows) ->
        require(rows.size == HEIGHT && rows.all { it.length == WIDTH }) { "Glyph '$c' hat kein 5×7-Raster" }
        val s = rows.joinToString("")
        BooleanArray(s.length) { s[it] == '#' }
    }

    val supported: Set<Char> get() = glyphs.keys

    /** Liefert die Punkte eines Zeichens (Zeile für Zeile). Unbekannte Zeichen werden als "?" dargestellt. */
    fun glyph(c: Char): BooleanArray {
        val key = when {
            c in glyphs -> c
            c.uppercaseChar() in glyphs -> c.uppercaseChar()
            c == 'ä' -> 'Ä'
            c == 'ö' -> 'Ö'
            c == 'ü' -> 'Ü'
            else -> '?'
        }
        return glyphs.getValue(key)
    }

    fun isOn(c: Char, col: Int, row: Int): Boolean = glyph(c)[row * WIDTH + col]

    /** Breite eines Textes in Punkten (inkl. 1 Punkt Abstand zwischen Zeichen). */
    fun widthInDots(text: String, spacing: Int = 1): Int =
        if (text.isEmpty()) 0 else text.length * WIDTH + (text.length - 1) * spacing
}
